#!/usr/bin/env python3
"""Man page and shell completions of the mb3d command line program.

    python3 tools/cli_docs.py HELP_DIR OUTDIR

writes OUTDIR/man/mb3d.1 and OUTDIR/completions/{mb3d.bash,_mb3d,mb3d.fish}
from the program's own help texts, saved in HELP_DIR as version.txt
(mb3d --version), main.txt (mb3d --help) and COMMAND.txt (mb3d COMMAND
--help), so the files always match the program they ship with. The release
workflow saves the texts and runs this for the Linux and macOS archives:

    mkdir help && ./mb3d --version > help/version.txt && ./mb3d --help > help/main.txt
    for c in animate batch voxel mesh mutagen montecarlo; do ./mb3d $c --help > help/$c.txt; done
"""
import os
import re
import sys

# the commands and their other names (main.rs, run())
COMMANDS = {
    "animate": ["anim"],
    "batch": [],
    "voxel": ["voxels"],
    "mesh": [],
    "mutagen": [],
    "montecarlo": ["mc"],
}

OPT = re.compile(r"^ {4}(?:(-[A-Za-z]), )?\s*(--[A-Za-z0-9-]+)(?:\s+<([^>]+)>)?\s*(.*)$")


def help_text(help_dir, command="main"):
    with open(os.path.join(help_dir, command + ".txt")) as f:
        return f.read()


def options(text):
    """(short, long, argument, first line of the description) of each option."""
    out = []
    for line in text.splitlines():
        m = OPT.match(line)
        if m:
            out.append((m.group(1), m.group(2), m.group(3), m.group(4).strip()))
    return out


def arg_kind(arg):
    if not arg:
        return None
    a = arg.upper()
    if "DIR" in a:
        return "dir"
    if "FILE" in a:
        return "file"
    return "value"


# ---------------------------------------------------------------- man page

def roff(line):
    line = line.replace("\\", "\\e").replace("-", "\\-")
    if line.startswith((".", "'")):
        line = "\\&" + line
    return line


def man_section(text):
    """A help text as man page sections: its CAPITALS: headings become
    headings, everything else stays as laid out in the help."""
    out, body = [], []

    def flush():
        while body and not body[-1].strip():
            body.pop()
        if body:
            out.append(".nf")
            out.extend(roff(l) for l in body)
            out.append(".fi")
        body.clear()

    for line in text.splitlines():
        m = re.match(r"^([A-Z][A-Z ]+):$", line)
        if m:
            flush()
            out.append(f'.SS "{m.group(1)}"')
        else:
            body.append(line)
    flush()
    return out


def man_page(help_dir, version):
    main = help_text(help_dir)
    first, _, rest = main.partition("\n")
    lines = [
        f'.TH MB3D 1 "" "mb3d-rs {version}" "User Commands"',
        ".SH NAME",
        roff(first.strip()),
        ".SH DESCRIPTION",
    ]
    lines += man_section(rest)
    for cmd in COMMANDS:
        t = help_text(help_dir, cmd)
        head, _, body = t.partition("\n")
        lines.append(f'.SH "{cmd.upper()}"')
        lines.append(roff(head.strip()))
        lines += man_section(body)
    lines += [
        ".SH ENVIRONMENT",
        ".TP",
        ".B MB3D_FORMULAS",
        "Folders with .m3f formula files (separated like PATH).",
        ".TP",
        ".B MB3D_MAPS",
        "Folders with maps and background pictures.",
        ".TP",
        ".B MB3D_GPU",
        "0 calculates on the CPU only (as \\-\\-cpu).",
        ".TP",
        ".B MB3D_PORTABLE",
        "1 keeps settings and History next to the program, 0 in ~/.config/mb3d\\-rs and",
        "~/.local/share/mb3d\\-rs (default: next to the program when its folder is writable).",
        ".SH SEE ALSO",
        "https://github.com/thr32423/mb3d-rs",
    ]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- bash

def bash(main_opts, cmd_opts):
    def case_for(opts):
        words = " ".join(w for s, l, _, _ in opts for w in ([s] if s else []) + [l])
        dirs = "|".join(w for s, l, a, _ in opts if arg_kind(a) == "dir" for w in ([s] if s else []) + [l])
        vals = "|".join(w for s, l, a, _ in opts if arg_kind(a) in ("file", "value") for w in ([s] if s else []) + [l])
        return words, dirs, vals

    out = [
        "# bash completion for mb3d (generated by tools/cli_docs.py)",
        "_mb3d() {",
        "    local cur prev cmd",
        '    cur="${COMP_WORDS[COMP_CWORD]}"',
        '    prev="${COMP_WORDS[COMP_CWORD-1]}"',
        '    cmd="${COMP_WORDS[1]}"',
        '    case "$cmd" in',
    ]
    for c, aliases in COMMANDS.items():
        words, dirs, vals = case_for(cmd_opts[c])
        out.append(f"        {'|'.join([c] + aliases)})")
        if dirs:
            out.append(f'            case "$prev" in {dirs}) COMPREPLY=($(compgen -d -- "$cur")); return;; esac')
        if vals:
            out.append(f'            case "$prev" in {vals}) COMPREPLY=($(compgen -f -- "$cur")); return;; esac')
        out.append(f'            if [[ "$cur" == -* ]]; then COMPREPLY=($(compgen -W "{words}" -- "$cur")); else COMPREPLY=($(compgen -f -- "$cur")); fi')
        out.append("            return;;")
    words, dirs, vals = case_for(main_opts)
    out.append("    esac")
    if vals:
        out.append(f'    case "$prev" in {vals}) COMPREPLY=($(compgen -f -- "$cur")); return;; esac')
    out.append(f'    if [[ "$cur" == -* ]]; then COMPREPLY=($(compgen -W "{words}" -- "$cur"));')
    out.append(f'    elif [[ $COMP_CWORD -eq 1 ]]; then COMPREPLY=($(compgen -W "{" ".join(COMMANDS)}" -- "$cur") $(compgen -f -- "$cur"));')
    out.append('    else COMPREPLY=($(compgen -f -- "$cur")); fi')
    out += ["}", "complete -o filenames -F _mb3d mb3d", ""]
    return "\n".join(out)


# ---------------------------------------------------------------- zsh

def zsh_desc(d):
    return re.sub(r"[\[\]:'\\]", "", d)


def zsh_specs(opts):
    specs = []
    for s, l, a, d in opts:
        k = arg_kind(a)
        action = {None: "", "dir": f":{a}:_files -/", "file": f":{a}:_files", "value": f":{a}: "}[k]
        desc = zsh_desc(d)
        if s:
            specs.append(f"'({s} {l})'{{{s},{l}}}'[{desc}]{action}'")
        else:
            specs.append(f"'{l}[{desc}]{action}'")
    return specs


def zsh(main_opts, cmd_opts):
    out = ["#compdef mb3d", "# zsh completion for mb3d (generated by tools/cli_docs.py)", "", "_mb3d() {"]
    out.append("  local -a cmds")
    out.append("  cmds=(" + " ".join(f"'{c}:{zsh_desc(help_line)}'" for c, help_line in CMD_LINES.items()) + ")")
    out.append('  case "${words[2]}" in')
    for c, aliases in COMMANDS.items():
        out.append(f"    {'|'.join([c] + aliases)})")
        out.append("      _arguments -s \\")
        for sp in zsh_specs(cmd_opts[c]):
            out.append(f"        {sp} \\")
        out.append("        '*:file:_files'")
        out.append("      ;;")
    out.append("    *)")
    out.append("      _arguments -s \\")
    for sp in zsh_specs(main_opts):
        out.append(f"        {sp} \\")
    out.append("        '1: :{_describe command cmds; _files}' \\")
    out.append("        '*:file:_files'")
    out.append("      ;;")
    out += ["  esac", "}", "", '_mb3d "$@"', ""]
    return "\n".join(out)


# ---------------------------------------------------------------- fish

def fish_q(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def fish(main_opts, cmd_opts):
    all_names = " ".join(n for c, a in COMMANDS.items() for n in [c] + a)
    out = ["# fish completion for mb3d (generated by tools/cli_docs.py)"]
    for c, line in CMD_LINES.items():
        out.append(f"complete -c mb3d -n __fish_use_subcommand -a {c} -d {fish_q(line)}")

    def opt_lines(cond, opts):
        for s, l, a, d in opts:
            parts = ["complete -c mb3d", f"-n {fish_q(cond)}"]
            if s:
                parts.append(f"-s {s[1:]}")
            parts.append(f"-l {l[2:]}")
            k = arg_kind(a)
            if k == "dir":
                parts.append("-x -a '(__fish_complete_directories)'")
            elif k:
                parts.append("-r")
            parts.append(f"-d {fish_q(d)}")
            out.append(" ".join(parts))

    opt_lines(f"not __fish_seen_subcommand_from {all_names}", main_opts)
    for c, aliases in COMMANDS.items():
        opt_lines(f"__fish_seen_subcommand_from {' '.join([c] + aliases)}", cmd_opts[c])
    return "\n".join(out) + "\n"


CMD_LINES = {}


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    help_dir, outdir = sys.argv[1], sys.argv[2]
    version = help_text(help_dir, "version").split()[-1]
    main_opts = options(help_text(help_dir))
    cmd_opts = {}
    for c in COMMANDS:
        t = help_text(help_dir, c)
        cmd_opts[c] = options(t)
        # "mb3d animate - render the frames ..." -> its description
        CMD_LINES[c] = t.splitlines()[0].split(" - ", 1)[-1].strip()
    os.makedirs(os.path.join(outdir, "man"), exist_ok=True)
    os.makedirs(os.path.join(outdir, "completions"), exist_ok=True)
    files = {
        "man/mb3d.1": man_page(help_dir, version),
        "completions/mb3d.bash": bash(main_opts, cmd_opts),
        "completions/_mb3d": zsh(main_opts, cmd_opts),
        "completions/mb3d.fish": fish(main_opts, cmd_opts),
    }
    for name, text in files.items():
        with open(os.path.join(outdir, name), "w") as f:
            f.write(text)
        print(f"wrote {os.path.join(outdir, name)}")


if __name__ == "__main__":
    main()
