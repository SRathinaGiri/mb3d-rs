//! Developer tool: translates the machine code of `.m3f` formula files into
//! Rust (`src/native.rs`), so the formulas run as compiled native code on
//! any CPU the crate is built for.
//!
//! usage: m3f2rs <formula dir> [-o src/native.rs]
//!
//! Every formula that the micro-op compiler accepts is translated.  At run
//! time a formula is matched by a hash of its code bytes; formulas without a
//! translation (new files, or code the compiler does not accept) keep
//! running in the interpreter.

use mb3d::custom::{build_machine, code_addr, CustomFormula};
use mb3d::m3f::M3f;
use std::collections::BTreeMap;
use std::fmt::Write;
use std::sync::Arc;

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let mut dir = None;
    let mut out = "src/native.rs".to_string();
    let mut i = 0;
    while i < args.len() {
        if args[i] == "--list" {
            // print the decoded instructions of one formula file
            let def = M3f::load(std::path::Path::new(&args[i + 1])).expect("m3f");
            for l in mb3d::x86::decode_listing(&def.code, mb3d::custom::code_addr(0)) {
                println!("{l}");
            }
            return;
        }
        if args[i] == "--gpu-report" {
            gpu_report(&args[i + 1]);
            return;
        }
        if args[i] == "--lift-report" {
            lift_report(&args[i + 1], args.get(i + 2).is_some_and(|a| a == "-v"));
            return;
        }
        if args[i] == "-o" {
            out = args[i + 1].clone();
            i += 2;
        } else {
            dir = Some(args[i].clone());
            i += 1;
        }
    }
    let dir = dir.expect("usage: m3f2rs <formula dir> [-o src/native.rs]");
    let mut files: Vec<_> = std::fs::read_dir(&dir)
        .expect("formula dir")
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|e| e.eq_ignore_ascii_case("m3f")))
        .collect();
    files.sort();
    // hash -> (op count, function name, formula names, code, direct version, dIFS)
    type Func = (usize, String, Vec<String>, String, bool, bool);
    let mut funcs: BTreeMap<u64, Func> = BTreeMap::new();
    let (mut skipped, mut total, mut lifted) = (0, 0, 0);
    for f in &files {
        total += 1;
        let Ok(def) = M3f::load(f) else {
            skipped += 1;
            continue;
        };
        let name = def.name.clone();
        let difs = def.de_option >= 20;
        let cf = CustomFormula::new(Arc::new(def));
        let m = build_machine(&[Some(&cf)]);
        let Some(p) = m.prog(code_addr(0)) else {
            skipped += 1;
            continue;
        };
        if p.emit_lifted("x", difs).is_some_and(|c| c.contains("map_px")) {
            // map formulas: the lifted version calls the map directly (no
            // stack arguments), not yet checked against the interpreter
            skipped += 1;
            continue;
        }
        let no_lift = std::env::var_os("M3F2RS_NO_LIFT").is_some();
        let e = funcs.entry(p.hash).or_insert_with(|| {
            let fname = format!("f_{:016x}", p.hash);
            // the lifted version (memory as locals) where the analysis
            // allows it, called directly with the iteration state except for
            // dIFS formulas; the emulated memory otherwise
            let lifted_code = if no_lift { None } else { p.emit_lifted(&fname, difs) };
            if lifted_code.is_some() {
                lifted += 1;
            }
            let (code, direct) = match lifted_code {
                Some(_) if !difs => (p.emit_lifted_direct(&fname).expect("lifted"), true),
                Some(c) => (c, false),
                None => (p.emit_rust(&fname, difs), false),
            };
            (p.len(), fname.clone(), Vec::new(), code, direct, difs)
        });
        // the same code used with both calling conventions would need both
        // versions
        assert_eq!(e.5, difs, "{name}: the same code as a formula of the other kind");
        e.2.push(name);
    }
    let mut o = String::new();
    o.push_str(
        "//! Formula code translated to Rust ahead of time.\n\
         //! GENERATED by `cargo run --release --bin m3f2rs -- <M3Formulas dir>`; do not edit.\n\
         #![allow(clippy::all, unused_mut, unused_variables, unreachable_code, unused_parens, unused_braces, unused_assignments)]\n\n\
         use super::*;\n\n",
    );
    let table = |o: &mut String, direct: bool| {
        let (fname, ty) = if direct { ("lookup_direct", "DirectFn") } else { ("lookup", "NativeFn") };
        let _ = writeln!(o, "pub(super) fn {fname}(hash: u64, ops: usize) -> Option<{ty}> {{\n    let (n, f): (usize, {ty}) = match hash {{");
        for (h, (n, fname, names, _, d, _)) in &funcs {
            if *d == direct {
                let _ = writeln!(o, "        {h:#018x} => ({n}, {fname}), // {}", names.join(", "));
            }
        }
        o.push_str("        _ => return None,\n    };\n    (n == ops).then_some(f)\n}\n\n");
    };
    table(&mut o, false);
    table(&mut o, true);
    for (_, (_, _, names, code, _, _)) in &funcs {
        let _ = writeln!(o, "// {}", names.join(", "));
        o.push_str(code);
        o.push('\n');
    }
    std::fs::write(&out, o).expect("write output");
    eprintln!(
        "{total} formula files: {} translated functions ({} files, {lifted} functions lifted), {skipped} not compilable",
        funcs.len(),
        funcs.values().map(|v| v.2.len()).sum::<usize>()
    );
}

/// `--lift-report DIR [-v]`: the lifting analysis of every formula (which
/// memory each access touches); lists the formulas that cannot be lifted.
fn lift_report(dir: &str, verbose: bool) {
    use mb3d::x86::lift::Loc;
    let mut files: Vec<_> = std::fs::read_dir(dir)
        .expect("formula dir")
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|e| e.eq_ignore_ascii_case("m3f")))
        .collect();
    files.sort();
    let (mut ok, mut bad, mut skipped) = (0, 0, 0);
    let mut reasons: BTreeMap<String, usize> = BTreeMap::new();
    let mut fields: BTreeMap<(u32, bool), usize> = BTreeMap::new();
    for f in &files {
        let Ok(def) = M3f::load(f) else {
            skipped += 1;
            continue;
        };
        let name = def.name.clone();
        let difs = def.de_option >= 20;
        let cf = CustomFormula::new(Arc::new(def));
        let m = build_machine(&[Some(&cf)]);
        let Some(p) = m.prog(code_addr(0)) else {
            skipped += 1;
            continue;
        };
        let r = p.lift_report(difs);
        for (_, l, w) in &r.accesses {
            if let Loc::Field(o) = l {
                *fields.entry((*o, *w)).or_default() += 1;
            }
        }
        if r.problems.is_empty() {
            ok += 1;
            if verbose {
                println!("OK    {name}: {} ops, {} accesses", r.ops, r.accesses.len());
            }
        } else {
            bad += 1;
            println!("NO    {name}: {}", r.problems.iter().take(3).cloned().collect::<Vec<_>>().join("; "));
            for p in &r.problems {
                // the kind of problem without the op number
                let kind = p.split_once(": ").map(|x| x.1).unwrap_or(p);
                let kind: String = kind.chars().take(40).collect();
                *reasons.entry(kind).or_default() += 1;
            }
        }
    }
    println!("\n{} formula files: {ok} liftable, {bad} not, {skipped} not compiled", files.len());
    println!("problem kinds:");
    let mut v: Vec<_> = reasons.into_iter().collect();
    v.sort_by(|a, b| b.1.cmp(&a.1));
    for (k, n) in v.iter().take(15) {
        println!("  {n:5}  {k}");
    }
    println!("iteration record fields used (offset, write: count):");
    for ((o, w), n) in fields {
        print!(" {o}{}:{n}", if w { "w" } else { "" });
    }
    println!();
}

/// `--gpu-report DIR`: how the lifted formulas map to 32-bit GPU values.
fn gpu_report(dir: &str) {
    let mut files: Vec<_> = std::fs::read_dir(dir)
        .expect("formula dir")
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|e| e.eq_ignore_ascii_case("m3f")))
        .collect();
    files.sort();
    let (mut clean, mut mixed_only, mut sse, mut not_lifted) = (0, 0, 0, 0);
    let mut patterns: BTreeMap<String, usize> = BTreeMap::new();
    for f in &files {
        let Ok(def) = M3f::load(f) else { continue };
        let name = def.name.clone();
        // GPU_REPORT_DIFS: the dIFS calling convention for every formula
        let difs = def.de_option >= 20 || std::env::var_os("GPU_REPORT_DIFS").is_some();
        let cf = CustomFormula::new(Arc::new(def));
        let m = build_machine(&[Some(&cf)]);
        let Some(p) = m.prog(code_addr(0)) else { continue };
        // GPU_REPORT_WGSL: also attempt the WGSL translation (LIFT_DEBUG says why it fails)
        if std::env::var_os("GPU_REPORT_WGSL").is_some() {
            println!("WGSL {} {name}", if p.emit_wgsl("f", difs).is_some() { "ok  " } else { "FAIL" });
        }
        match p.gpu_typing(difs) {
            None => not_lifted += 1,
            Some((true, _)) => {
                sse += 1;
                println!("SSE   {name}");
            }
            Some((false, mixed)) if mixed.is_empty() => {
                clean += 1;
                println!("PLAIN {name}");
            }
            Some((false, mixed)) => {
                mixed_only += 1;
                println!("MIXED {name}: {}", mixed.join("; "));
                for m in &mixed {
                    let pat = m.split_once(": ").map(|x| x.1.to_string()).unwrap_or_default();
                    *patterns.entry(pat).or_default() += 1;
                }
            }
        }
    }
    println!("\nnot lifted {not_lifted}, with SSE {sse}, plain {clean}, with mixed cells {mixed_only}");
    let mut v: Vec<_> = patterns.into_iter().collect();
    v.sort_by(|a, b| b.1.cmp(&a.1));
    println!("mixed cell patterns (kind@offset x bytes):");
    for (p, n) in v.iter().take(20) {
        println!("  {n:4}  {p}");
    }
}
